create table public.gift_watch_history (
  id bigint generated by default as identity primary key,
  chat_id text not null,
  access_hash text not null,
  kind text not null check (kind in ('offer', 'upgrade')),
  event_key text not null,
  title text not null,
  market text,
  price_ton numeric,
  floor_ton numeric,
  model text,
  backdrop text,
  owner_username text,
  basis text,
  target_url text,
  preview_url text,
  extra jsonb not null default '{}'::jsonb,
  sold boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (chat_id, kind, event_key)
);

alter table public.gift_watch_history enable row level security;
revoke all on table public.gift_watch_history from anon, authenticated;
revoke all on sequence public.gift_watch_history_id_seq from anon, authenticated;

create index gift_watch_history_access_kind_created_idx
  on public.gift_watch_history (access_hash, kind, created_at desc);

comment on table public.gift_watch_history is
  'Private per-chat alert history, available only through the authenticated history Edge Function.';

create table public.gift_watch_settings (
  chat_id text primary key,
  access_hash text not null unique,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.gift_watch_settings enable row level security;
revoke all on table public.gift_watch_settings from anon, authenticated;

comment on table public.gift_watch_settings is
  'Durable per-chat monitor settings, available only through the authenticated Mini App Edge Function.';
